"""Export runbooks to Markdown."""

from __future__ import annotations

from datetime import datetime

from ..runbook.models import Runbook


class MarkdownExporter:
    """Converts a completed runbook to a Markdown document."""

    @staticmethod
    def export(runbook: Runbook) -> str:
        lines = [
            f"# DevFlow Runbook: #{runbook.ticket_id} — {runbook.ticket_title}",
            "",
            f"**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M')}",
            f"**AI Provider:** {runbook.ai_provider}",
            f"**Codebase Aware:** {'Yes' if runbook.codebase_aware else 'No'}",
            f"**Progress:** {runbook.completed_steps}/{len(runbook.steps)} "
            f"steps ({runbook.progress}%)",
            "",
            "---",
            "",
            "## Implementation Steps",
            "",
        ]

        user_step_num = 0
        for step in runbook.steps:
            if step.is_git_step:
                icon = "✅" if step.is_completed else "⬜"
                lines.append(f"**{icon} [{step.title}]**")
            else:
                user_step_num += 1
                icon = "✅" if step.is_completed else "⬜"
                lines.append(f"### {user_step_num}. {icon} {step.title}")

            if step.description:
                lines.append(f"  {step.description}")
            if step.time_spent_seconds > 0:
                mins = int(step.time_spent_seconds // 60)
                lines.append(f"  *Time spent: {mins} min*")
            lines.append("")

        total_mins = int(runbook.total_time_seconds // 60)
        lines.extend([
            "---",
            "",
            f"**Total time:** {total_mins} minutes",
            "",
            "*Generated by DevFlow for VS Code*",
        ])

        return "\n".join(lines)
